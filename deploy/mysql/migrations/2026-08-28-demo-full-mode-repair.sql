-- 身份申请早于区域代理申请时，历史线索可能停在“待分配”。本次只把它分给同区域
-- 最早启用的区域代理并进入24小时待确认；确认后才建立冻结归属链，资金关系不越过用户动作。
UPDATE `ws_public_lead` l
JOIN (
  SELECT l0.ID AS LEAD_ID, MIN(p.ID) AS PROFILE_ID
  FROM `ws_public_lead` l0
  JOIN `ws_identity_profile` p
    ON p.CAPABILITY_TYPE=4
   AND p.PROFILE_STATUS=1
   AND p.DATA_STATUS=0
   AND p.REGION_NAME=l0.REGION_NAME
  WHERE l0.DATA_STATUS=0
    AND l0.LEAD_STATUS=1
    AND l0.ASSIGNED_PROFILE_ID IS NULL
  GROUP BY l0.ID
) x ON x.LEAD_ID=l.ID
SET l.ASSIGNED_PROFILE_ID=x.PROFILE_ID,
    l.LEAD_STATUS=2,
    l.ASSIGNED_TIME=DATE_FORMAT(DATE_ADD(UTC_TIMESTAMP(),INTERVAL 8 HOUR),'%Y%m%d%H%i%s'),
    l.RESPONSE_DEADLINE=DATE_FORMAT(DATE_ADD(UTC_TIMESTAMP(),INTERVAL 32 HOUR),'%Y%m%d%H%i%s'),
    l.ASSIGN_ROUND=IFNULL(l.ASSIGN_ROUND,0)+1
WHERE l.DATA_STATUS=0
  AND l.LEAD_STATUS=1
  AND l.ASSIGNED_PROFILE_ID IS NULL;
